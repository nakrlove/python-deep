import pandas as pd

########################################
# pip install prophet
# 설치를 해 주세요
########################################
from prophet import Prophet

# 데이터 불러오기
file_path = 'C:\\Users\\Admin\\study01\\20250819\\아파트(전월세)_실거래가_20250819144737-ver0.2.csv'
df_rent = pd.read_csv(file_path, encoding='utf-8', sep=';')

# 데이터 전처리 및 월별 거래량 집계
df_monthly = df_rent.groupby('계약년월').size().reset_index(name='거래량')
df_monthly['계약년월'] = pd.to_datetime(df_monthly['계약년월'], format='%Y%m')

# Prophet 모델을 위한 데이터프레임 변환
df_prophet = df_monthly.rename(columns={'계약년월': 'ds', '거래량': 'y'})


# Prophet 모델 학습
#########################################################################
# Prophet의 역할
# Prophet 은 Facebook(메타)이 개발한 <시계열 예측> 라이브러리입니다.
# 즉, "시간 흐름에 따라 변하는 데이터"를 예측하는 데 특화되어 있습니다.
#   예:
#     아파트 가격의 월별 변동
#     부동산 거래량의 계절적 변화
#     특정 지역 전세가의 장기 추세
# ========================================================================
# Prophet의 특징
# 1. 추세(Trend)
#    장기적으로 증가/감소하는 흐름을 모델링합니다.
#    예: 아파트 가격이 장기적으로 상승 추세인지 하락 추세인지.
# =======================================================================
# 2. 계절성(Seasonality)
#    주기적인 패턴을 잡습니다. (월별, 분기별, 연간)
#    예: 부동산 거래는 35월, 910월에 많고 1월, 7월은 적음.
# =======================================================================
# 3. 휴일 효과(Holiday / Event)
#    특정 이벤트가 데이터에 영향을 주는 효과를 반영합니다.
#    예: 부동산 대출 규제 시행, 코로나19, 명절 시즌 등.
# =======================================================================
# Prophet
# → 딥러닝만큼 복잡하지 않고, 머신러닝처럼 일반 피처(feature)도 필요 없음.
# → 시간 흐름만 가지고도 빠르고 직관적인 시계열 예측이 가능.
# → "데이터 사이언티스트가 아니더라도 쉽게 쓸 수 있는 시계열 예측 도구"
#########################################################################
model_prophet = Prophet(changepoint_prior_scale=0.01)
model_prophet.fit(df_prophet)

# 미래 12개월 예측
future_dates = model_prophet.make_future_dataframe(periods=12, freq='ME')
forecast_monthly = model_prophet.predict(future_dates)

# 예측 결과 출력
# Prophet predict() 결과 주요 컬럼
# 1. ds
#   날짜(time stamp)
#   예측 기준이 되는 시점 (datetime 형식)
# 2. yhat
#   Prophet이 예측한 값 (point forecast)
#   예: 아파트 평균 거래금액 예측치
# 3. yhat_lower / yhat_upper
#   예측 구간의 하한 / 상한 (95% 신뢰구간, 기본값)
#   즉, 예측치의 불확실성을 보여줌
print("### 월별 전월세 거래량 예측 결과 (Prophet)\n")
print(forecast_monthly[['ds', 'yhat', 'yhat_lower', 'yhat_upper']].tail())



